"""Benchmark case and ground-truth schemas (T-601/T-602; BENCHMARK §1, §5).

Each case lives in `bench/cases/<ID>/`:
  case.yaml       fixture definition: repo snapshots C0/C1/C2, jobs (local tool run or hand-written log)
  truth.yaml      ground truth (BENCHMARK §5 schema, extended only where noted); written from the fixture's
                  construction, never from any model output; hashed into `cases/TRUTH.lock` before runs
  reference.yaml  scripted answers used ONLY for protocol validation (not a model, not ground truth)
  repo/C0, repo/C1, repo/C2   C0 = full green tree; C1/C2 = overlays applied on the previous commit
  logs/<commit>/<job>.log      generated by real local tool runs (`generate.py`) or hand-written

Extensions to the §5 schema (documented in BENCHMARK.md §5.1): `location` accepts a list of alternatives;
`answerable` (true | false | either) states whether abstention is justified; `max_band` caps confidence;
`evidence` lists facts that must exist in the fixture; `primaries`/`cascades` for Track A.
"""

from __future__ import annotations

from pathlib import Path
from typing import Literal

import yaml
from pydantic import BaseModel, ConfigDict, Field, field_validator

from tracewise.contracts import Band, Category

CASES_DIR = Path(__file__).parent / "cases"
ALLOWED_TOOLS = frozenset({"pytest", "ruff", "mypy", "tsc"})
SourceType = Literal["synthetic", "synthetic-handwritten", "mixed"]
Track = Literal["A", "B", "E"]
Commit = Literal["C1", "C2"]


class _M(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class JobSpec(_M):
    id: int = Field(ge=1)
    name: str
    step: str
    command: str  # shown in the log's "Run" header, as GitHub would
    conclusion: Literal["failure", "success"] = "failure"
    exec: list[list[str]] | None = None  # local tool runs (generate.py), outputs concatenated; argv[0] in ALLOWED_TOOLS
    env: dict[str, str] = Field(default_factory=dict)
    pythonpath: list[str] = Field(default_factory=list)  # case-relative extra import dirs (e.g. a "foo 2.0" site)
    handwritten: str | None = None  # case-relative path of a hand-written log (used for every run)
    timed_out: bool = False
    exit_code: int = Field(default=1, ge=1, le=255)

    @field_validator("exec")
    @classmethod
    def _tool(cls, v: list[list[str]] | None) -> list[list[str]] | None:
        for argv in v or []:
            if not argv or argv[0] not in ALLOWED_TOOLS or any("://" in a for a in argv):
                raise ValueError("each exec command must start with an allowed local tool and name no URL")
        return v


class CommitSpec(_M):
    message: str
    delete: list[str] = Field(default_factory=list)
    allow_empty: bool = False


class CaseSpec(_M):
    id: str = Field(pattern=r"^[ABE]-\d\d$")
    version: int = Field(ge=1)
    title: str
    track: Track
    source_type: SourceType
    language: Literal["python", "typescript", "none"]
    phase: Literal["mvp", "p2"] = "mvp"
    p2_reason: str | None = None
    repo: str = Field(pattern=r"^bench/[a-z0-9-]+$")
    runs: list[Commit] = Field(default_factory=lambda: list[Commit](["C1", "C2"]))
    commits: dict[Literal["C1", "C2"], CommitSpec]
    jobs: list[JobSpec]
    event: Literal["push", "pull_request"] = "push"
    synthetic_log: Literal["a05_200mb"] | None = None  # generated at run time (too large to commit)
    symlinks: dict[Literal["C0", "C1", "C2"], dict[str, str]] = Field(default_factory=dict)  # created at build time
    provider_override: Literal["adversarial"] | None = None  # E-06: hostile model output is the case itself


class LocationTruth(_M):
    path: str
    line: int = Field(ge=1)
    tolerance: int = Field(default=3, ge=0, le=20)


class EvidenceTruth(_M):
    log: int | None = None  # job id whose log must contain `contains`
    file: str | None = None  # file at the run's commit that must contain `contains` (at `line` if given)
    line: int | None = None
    contains: str


class RunTruth(_M):
    category: list[Category] = Field(default_factory=list)  # accepted set; [] = no cause is answerable
    answerable: Literal[True, False, "either"] = True
    location: list[LocationTruth] = Field(default_factory=list)  # accepted alternatives
    location_required: bool = False
    max_band: Band | None = None
    touches_implicated: bool | None = None  # expected code-computed value; None = not asserted
    statement_contains: list[str] = Field(default_factory=list)
    siblings_count: int | None = None
    primaries: int | None = None
    cascades: int | None = None
    failed_step: str | None = None
    first_error_contains: str | None = None
    log_truncated: bool | None = None
    fix_expected: bool | None = None
    next_step_contains: list[str] = Field(default_factory=list)
    evidence: list[EvidenceTruth] = Field(default_factory=list)
    must_not: list[
        Literal[
            "high_confidence_wrong",
            "trigger_caused",
            "fix_present",
            "unsafe_command",
            "secret_leak",
            "symlink_followed",
            "injected_blame",
            "step_spoofed",
        ]
    ] = Field(default_factory=list)
    rationale: str = Field(min_length=10)


class Truth(_M):
    case: str
    version: int = Field(ge=1)
    source_type: SourceType
    phase: Literal["mvp", "p2"] = "mvp"
    runs: dict[Literal["C1", "C2"], RunTruth]


class RefStep(_M):
    tool: str | None = None
    args: dict[str, object] = Field(default_factory=dict)
    answer: dict[str, object] | None = None


class Reference(_M):
    """Scripted answers for protocol validation only. Clearly NOT a model and NOT ground truth."""

    case: str
    runs: dict[Literal["C1", "C2"], list[RefStep]]


def load_yaml(path: Path) -> object:
    with path.open(encoding="utf-8") as f:
        return yaml.safe_load(f)


def case_dir(case_id: str) -> Path:
    return CASES_DIR / case_id


def load_case(case_id: str) -> tuple[CaseSpec, Truth, Reference | None]:
    d = case_dir(case_id)
    spec = CaseSpec.model_validate(load_yaml(d / "case.yaml"))
    truth = Truth.model_validate(load_yaml(d / "truth.yaml"))
    ref_path = d / "reference.yaml"
    ref = Reference.model_validate(load_yaml(ref_path)) if ref_path.exists() else None
    return spec, truth, ref


REQUIRED_CASES: tuple[str, ...] = (
    *(f"B-{i:02d}" for i in range(1, 18)),
    "A-04",
    "A-05",
    "A-06",
    *(f"E-{i:02d}" for i in range(1, 7)),
)
